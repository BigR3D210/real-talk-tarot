export const getCardById = (id: string): TarotCard | undefined =>
  tarotDeck.find(card => card.id === id);

export const getMajorArcana = (): TarotCard[] =>
  tarotDeck.filter(card => card.arcana === 'major');

export const getMinorArcana = (): TarotCard[] =>
  tarotDeck.filter(card => card.arcana === 'minor');

export const getCardsBySuit = (suit: TarotCard['suit']): TarotCard[] =>
  tarotDeck.filter(card => card.suit === suit);
